app.post("/api/auth/register", async (req, res) => {
  const {
    role,
    email,
    password,
    firstName,
    middleName,
    lastName,
    businessName,
    agreeTerms,
  } = req.body ?? {};

  if (role !== "applicant" && role !== "employer") {
    res.status(400).json({ message: "Invalid role." });
    return;
  }

  if (typeof email !== "string" || !email.trim()) {
    res.status(400).json({ message: "Email is required." });
    return;
  }

  if (!isValidPassword(password)) {
    res.status(400).json({ message: "Password does not meet the required strength." });
    return;
  }

  if (!agreeTerms) {
    res.status(400).json({ message: "You must accept terms and privacy policy." });
    return;
  }

  if (role === "applicant") {
    if (
      typeof firstName !== "string" || !firstName.trim() ||
      typeof lastName !== "string" || !lastName.trim()
    ) {
      res.status(400).json({ message: "First name and last name are required for applicants." });
      return;
    }
  }

  if (role === "employer") {
    if (typeof businessName !== "string" || !businessName.trim()) {
      res.status(400).json({ message: "Business name is required for employers." });
      return;
    }
  }

  try {
    const existing = await get("SELECT id FROM users WHERE email = ?", [email.trim().toLowerCase()]);
    if (existing) {
      res.status(409).json({ message: "An account with this email already exists." });
      return;
    }

    const passwordHash = await bcrypt.hash(password, 10);

    await run("BEGIN TRANSACTION");

    const userInsert = await run(
      "INSERT INTO users (email, password_hash, role, is_active) VALUES (?, ?, ?, 1)",
      [email.trim().toLowerCase(), passwordHash, role]
    );

    const userId = userInsert.lastID;

    if (role === "applicant") {
      await run(
        `INSERT INTO applicant_profiles
          (user_id, first_name, middle_name, last_name, terms_accepted, terms_accepted_at)
         VALUES (?, ?, ?, ?, 1, datetime('now'))`,
        [userId, firstName.trim(), (middleName ?? "").trim() || null, lastName.trim()]
      );
    } else {
      await run(
        `INSERT INTO employer_profiles
          (user_id, business_name, terms_accepted, terms_accepted_at)
         VALUES (?, ?, 1, datetime('now'))`,
        [userId, businessName.trim()]
      );
    }

    await run("COMMIT");

    res.status(201).json({
      message: "Account created successfully.",
      user: {
        id: userId,
        role,
        email: email.trim().toLowerCase(),
      },
    });
  } catch (error) {
    try {
      await run("ROLLBACK");
    } catch {
      // Ignore rollback errors.
    }

    res.status(500).json({ message: "Registration failed. Please try again." });
  }
});

app.post("/api/auth/login", async (req, res) => {
  const { role, email, password } = req.body ?? {};

  if (role !== "applicant" && role !== "employer") {
    res.status(400).json({ message: "Invalid role." });
    return;
  }

  if (typeof email !== "string" || !email.trim()) {
    res.status(400).json({ message: "Email is required." });
    return;
  }

  if (typeof password !== "string" || !password) {
    res.status(400).json({ message: "Password is required." });
    return;
  }

  try {
    const user = await get(
      "SELECT id, email, password_hash, role, is_active FROM users WHERE email = ?",
      [email.trim().toLowerCase()]
    );

    if (!user) {
      res.status(401).json({ message: "Invalid email or password." });
      return;
    }

    if (!user.is_active) {
      res.status(403).json({ message: "Account is inactive." });
      return;
    }

    if (user.role !== role) {
      res.status(403).json({ message: `This account is registered as ${user.role}.` });
      return;
    }

    const passwordMatches = await bcrypt.compare(password, user.password_hash);
    if (!passwordMatches) {
      res.status(401).json({ message: "Invalid email or password." });
      return;
    }

    let businessName = null;
    if (user.role === "employer") {
      const employerProfile = await get(
        "SELECT * FROM employer_profiles WHERE user_id = ?",
        [user.id]
      );
      businessName =
        employerProfile?.business_name ??
        employerProfile?.company_name ??
        employerProfile?.businessName ??
        null;
    }

    res.status(200).json({
      message: "Login successful.",
      user: {
        id: user.id,
        email: user.email,
        role: user.role,
        businessName,
      },
    });
  } catch {
    res.status(500).json({ message: "Login failed. Please try again." });
  }
});

