function isValidPassword(password) {
  return (
    typeof password === "string" &&
    password.length >= 8 &&
    /[A-Z]/.test(password) &&
    /[a-z]/.test(password) &&
    /\d/.test(password)
  );
}

function normalizeCurrency(value) {
  if (value === undefined || value === null) return null;
  const str = String(value);
  const raw = str.replace(/[^0-9.]/g, "").trim();
  if (!raw) return null;
  const amount = Number(raw);
  if (!Number.isFinite(amount) || amount < 0) return null;
  return amount.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
}

function parseCloseDate(value) {
  if (typeof value !== "string") return null;
  const raw = value.trim();
  const match = raw.match(/^(\d{2})\/(\d{2})\/(\d{4})$/);
  if (!match) return null;
  const month = Number(match[1]);
  const day = Number(match[2]);
  const year = Number(match[3]);
  if (month < 1 || month > 12 || day < 1 || day > 31 || year < 1900) return null;
  const date = new Date(year, month - 1, day);
  if (date.getFullYear() !== year || date.getMonth() !== month - 1 || date.getDate() !== day) return null;
  return raw;
}

function deriveJobPostStatus(closeDate) {
  const parsed = parseCloseDate(closeDate);
  if (!parsed) return "open";
  const [mm, dd, yyyy] = parsed.split("/").map(Number);
  const closeAt = new Date(yyyy, mm - 1, dd, 23, 59, 59, 999);
  return Date.now() <= closeAt.getTime() ? "open" : "closed";
}

