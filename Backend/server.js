      doc.fillColor("#0f172a").fontSize(18).text(row.resume_path ? `Resume: ${row.resume_path}` : "Candidate Resume");
      doc.moveDown(0.5);
      doc.strokeColor("#cbd5e1").lineWidth(1).moveTo(40, doc.y).lineTo(555, doc.y).stroke();
